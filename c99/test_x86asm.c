static void check_opcode_only(const uint8_t *bytes, size_t length, x86asm_opcode expected)
{
    x86asm_instruction instruction;
    assert(x86asm_decode(bytes, length, 64, &instruction) == X86ASM_OK);
    assert(instruction.opcode == expected);
}

static void check_error(const uint8_t *bytes, size_t length, x86asm_error expected)
{
    x86asm_instruction instruction;
    assert(x86asm_decode(bytes, length, 64, &instruction) == expected);
}

static void check(const uint8_t *bytes, size_t length, x86asm_opcode opcode,
                  const char *expected)
{
    x86asm_instruction instruction;
    char text[128];
    x86asm_error error = x86asm_decode(bytes, length, 64, &instruction);
    assert(error == X86ASM_OK);
    assert(instruction.opcode == opcode);
    x86asm_format_default(&instruction, text, sizeof(text));
    if (strcmp(text, expected) != 0) {
        fprintf(stderr, "expected: %s\nactual:   %s\n", expected, text);
        assert(0);
    }
    puts(text);
}

