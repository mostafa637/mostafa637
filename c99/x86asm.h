typedef enum x86asm_prefix {
    X86ASM_PREFIX_NONE = 0,
    X86ASM_PREFIX_LOCK = 0xF0,
    X86ASM_PREFIX_REPN = 0xF2,
    X86ASM_PREFIX_REP = 0xF3,
    X86ASM_PREFIX_CS = 0x2E,
    X86ASM_PREFIX_SS = 0x36,
    X86ASM_PREFIX_DS = 0x3E,
    X86ASM_PREFIX_ES = 0x26,
    X86ASM_PREFIX_FS = 0x64,
    X86ASM_PREFIX_GS = 0x65,
    X86ASM_PREFIX_DATA16 = 0x66,
    X86ASM_PREFIX_ADDR16 = 0x67,
    X86ASM_PREFIX_IGNORED = 0x4000,
    X86ASM_PREFIX_INVALID = 0x2000,
    X86ASM_PREFIX_IMPLICIT = 0x8000
} x86asm_prefix;

typedef enum x86asm_arg_kind {
    X86ASM_ARG_NONE = 0,
    X86ASM_ARG_REGISTER,
    X86ASM_ARG_MEMORY,
    X86ASM_ARG_IMMEDIATE,
    X86ASM_ARG_RELATIVE
} x86asm_arg_kind;

typedef struct x86asm_memory {
    x86asm_register segment;
    x86asm_register base;
    x86asm_register index;
    uint8_t scale;
    int64_t displacement;
} x86asm_memory;

typedef struct x86asm_argument {
    x86asm_arg_kind kind;
    union {
        x86asm_register reg;
        x86asm_memory memory;
        int64_t immediate;
        int32_t relative;
    } value;
} x86asm_argument;

typedef struct x86asm_instruction {
    x86asm_prefix prefixes[14];
    x86asm_opcode opcode;
    uint32_t encoded_opcode;
    x86asm_argument arguments[6];
    int mode;
    int address_size;
    int data_size;
    int memory_bytes;
    int length;
    int pc_relative_bytes;
    int pc_relative_offset;
    bool broadcast;
    bool zeroing;
    bool sae;
    int8_t rounding;
} x86asm_instruction;

x86asm_error x86asm_decode(const uint8_t *bytes, size_t length, int mode,
                           x86asm_instruction *instruction);

const char *x86asm_error_string(x86asm_error error);
const char *x86asm_register_name(x86asm_register reg);
const char *x86asm_opcode_name(x86asm_opcode opcode);

/* Returns the number of characters that would be written, excluding NUL. */
size_t x86asm_format_intel(const x86asm_instruction *instruction, uint64_t pc,
                           char *output, size_t output_size);
size_t x86asm_format_default(const x86asm_instruction *instruction,
                             char *output, size_t output_size);

