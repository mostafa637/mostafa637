//! Word-for-word differential test of `vec.rs` against the C original.
//!
//! `tests/fixtures/vec_reference.txt` is produced by `tools/vec-dump.c`,
//! compiled against the **unmodified** iSH `emu/vec.c` and `emu/mmx.c`. It
//! calls every one of the 166 functions `emu/vec.h` declares — the op table is
//! generated from that header by `tools/gen_vec_ops.py`, so nothing can be
//! quietly left out — over 50 operand cases chosen to hit the corners:
//! saturating arithmetic, signed and unsigned compares, shift counts just past
//! every element width, shuffle encodings, insert/extract indices, all eight
//! float-compare predicates, and NaN/±inf/denormal/overflow operands for the
//! conversions.
//!
//! After each call the C dumps the destination register, the source register,
//! a side buffer for the operations whose destination is a bare scalar, and
//! nine `cpu_state` flag fields. That last part is what proves only the two
//! `ucomi` operations touch the CPU at all.
//!
//! The dispatch match below is generated by the same script
//! (`tools/gen_vec_ops.py <ish> --rust`); an operation present in the fixture
//! but missing here panics on its name rather than passing silently.
//!
//! Regenerate with:
//!
//! ```text
//! ISH_SRC=/path/to/ish ./tools/gen_vec_reference.sh
//! ```

use std::collections::BTreeSet;

