const FIXTURE: &str = concat!(env!("CARGO_MANIFEST_DIR"), "/tests/fixtures/vec_reference.txt");

/// One operand case. The values come out of the fixture header, so the Rust
/// side never has to duplicate the C driver's tables.
#[derive(Clone, Copy, Debug)]
struct Case {
    src: [u8; 16],
    dst: [u8; 16],
    encoding: u8,
    index: u8,
    amount: u8,
    type_: u8,
}

fn hex16(fields: &[&str]) -> [u8; 16] {
    let mut out = [0u8; 16];
    for (i, f) in fields.iter().enumerate() {
        out[i] = u8::from_str_radix(f, 16).unwrap();
    }
    out
}

fn parse_fixture() -> (Vec<Case>, Vec<Vec<String>>) {
    let text = std::fs::read_to_string(FIXTURE)
        .unwrap_or_else(|e| panic!("cannot read {FIXTURE}: {e}"));
    let mut cases = Vec::new();
    let mut records = Vec::new();
    for line in text.lines() {
        if let Some(rest) = line.strip_prefix("# C ") {
            let f: Vec<&str> = rest.split(' ').collect();
            assert_eq!(f.len(), 1 + 32 + 4, "malformed case line");
            cases.push(Case {
                src: hex16(&f[1..17]),
                dst: hex16(&f[17..33]),
                encoding: u8::from_str_radix(f[33], 16).unwrap(),
                index: u8::from_str_radix(f[34], 16).unwrap(),
                amount: u8::from_str_radix(f[35], 16).unwrap(),
                type_: u8::from_str_radix(f[36], 16).unwrap(),
            });
        } else if line.starts_with("V ") {
            records.push(line.split(' ').map(|s| s.to_string()).collect());
        }
    }
    (cases, records)
}

