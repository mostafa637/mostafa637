#[test]
fn the_reference_actually_exercises_the_corners() {
    let (cases, records) = parse_fixture();
    // the case table has to carry the parameters the corner cases need
    let amounts: Vec<u8> = cases.iter().map(|c| c.amount).collect();
    for a in [0u8, 1, 15, 16, 31, 32, 63, 64, 127, 255] {
        assert!(amounts.contains(&a), "no case shifts by {a}");
    }
    let types: Vec<u8> = cases.iter().map(|c| c.type_).collect();
    for t in 0u8..8 {
        assert!(types.contains(&t), "no case uses float-compare predicate {t}");
    }
    let indices: Vec<u8> = cases.iter().map(|c| c.index).collect();
    for i in 0u8..8 {
        assert!(indices.contains(&i), "no case uses insert/extract index {i}");
    }

    // the NaN payload of the commutative arithmetic depends on which operand
    // the compiler puts in the destination register, so the corpus has to
    // contain cases where *both* operands are NaN - in both float widths
    let (mut nan64, mut nan32) = (0usize, 0usize);
    for c in &cases {
        let s = XmmReg::from_bytes(c.src);
        let d = XmmReg::from_bytes(c.dst);
        if (0..2).any(|i| s.f64(i).is_nan() && d.f64(i).is_nan()) {
            nan64 += 1;
        }
        if (0..4).any(|i| s.f32(i).is_nan() && d.f32(i).is_nan()) {
            nan32 += 1;
        }
    }
    assert!(nan64 > 0, "no case has both f64 operands NaN");
    assert!(nan32 > 0, "no case has both f32 operands NaN");

    // and the dumps must not be degenerate
    let nonzero = records
        .iter()
        .filter(|r| r[3..19].iter().any(|b| b != "00"))
        .count();
    assert!(
        nonzero > records.len() / 2,
        "only {nonzero} of {} destinations are non-zero",
        records.len()
    );
    let flags_set = records.iter().filter(|r| r[51..60].iter().any(|b| b != "0")).count();
    assert!(flags_set > 0, "no operation ever set a cpu flag");
}
